#!/usr/bin/env python3
"""Render, master, encode and QA every registered audio asset.

  python tools/audio-gen/build_all.py [--only GLOB ...] [--kind sfx|music|amb|stinger] [--jobs N] [--out DIR] [--check]

Outputs (relative to frontend/implementation):
  public/audio/{sfx,music,amb}/<file>.ogg      Opus in Ogg, 48 kHz
  public/audio/manifest.json                    machine-readable manifest (ids, durations, loudness, sha256, licence)
  src/audio/registry/assets.generated.ts        typed asset table consumed by the engine (do not edit by hand)

Deterministic: every asset uses an RNG seeded from its id, so the same script always yields the same samples.
Licence of all generated audio: original work created by this repository's scripts (no third-party samples, no AI audio model),
distributed under the repository licence (see LICENSE.md).
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import sys
import tempfile
import time
from concurrent.futures import ProcessPoolExecutor
from datetime import date
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from common import dsp, master  # noqa: E402
import registry  # noqa: E402

IMPL = HERE.parent.parent            # frontend/implementation
LICENSE_TEXT = "Original work generated by tools/audio-gen (numpy/scipy synthesis, no third-party samples, no AI audio model). Distributed under the repository licence (GNU AGPL-3.0, see LICENSE.md)."


def _load_all():
    import sfx  # noqa: F401
    import music  # noqa: F401


def render_one(args):
    sid, out_root = args
    _load_all()
    spec = registry.SPECS[sid]
    t0 = time.time()
    rng = dsp.rng_for(spec.id)
    x = spec.fn(rng)
    x = np.asarray(x, dtype=np.float64)
    if spec.kind == "sfx":
        x = master.finalize_sfx(x, spec.peak_db, stereo=spec.stereo)
        issues = master.qa_sfx(spec.id, x)
    elif spec.kind == "stinger":
        x = dsp.dc_block(dsp.to_stereo(x)); x = master.trim_silence(x, -70.0)
        x = dsp.fade(x, fin=0.002, fout=0.05, curve="lin"); x = dsp.normalize_peak(x, spec.peak_db)
        issues = master.qa_sfx(spec.id, x)
    else:                                        # music / amb loops
        n0 = x.shape[0]
        x = master.finalize_loop(x, spec.rms_db)
        assert x.shape[0] == n0
        issues = master.qa_loop(spec.id, x, relaxed=(spec.kind == "sfxloop"))
    sub = {"sfx": "sfx", "sfxloop": "sfx", "stinger": "music", "music": "music", "amb": "amb"}[spec.kind]
    ogg = Path(out_root) / sub / f"{spec.file}.ogg"
    with tempfile.TemporaryDirectory() as d:
        wav = Path(d) / "a.wav"
        master.write_wav(wav, x)
        master.encode_opus(wav, ogg, spec.kbps, "audio")
    dec = master.decode_to_array(ogg)
    # loop seam check on the DECODED file (what the browser will actually loop)
    if spec.loop:
        d2 = dsp.to_stereo(dec)
        seam = float(np.max(np.abs(d2[0] - d2[-1])))
        if seam > 0.05:
            issues.append(f"decoded loop seam {seam:.3f}")
    loud = master.ebur128(ogg)
    rec = {
        "id": spec.id, "file": f"audio/{sub}/{spec.file}.ogg", "kind": spec.kind, "group": spec.group, "bus": spec.bus, "loop": spec.loop,
        "channels": 2 if (x.ndim == 2) else 1, "sampleRate": dsp.SR, "samples": int(x.shape[0]), "duration": round(x.shape[0] / dsp.SR, 4),
        "bytes": ogg.stat().st_size, "sha256": master.sha256(ogg), "lufsI": loud["lufs_i"], "truePeakDb": loud["true_peak_db"],
        "peakDecoded": round(float(np.max(np.abs(dec))), 4), "desc": spec.desc, "meta": spec.meta, "qa": issues,
        "source": f"tools/audio-gen ({spec.fn.__module__}.{spec.fn.__name__})", "licence": "Original synthesis; distributed under the repository licence (AGPL-3.0, LICENSE.md)", "created": date.today().isoformat(),
        "seconds": round(time.time() - t0, 2),
    }
    return rec


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", nargs="*", default=[])
    ap.add_argument("--kind", choices=["sfx", "sfxloop", "music", "amb", "stinger"], default=None)
    ap.add_argument("--jobs", type=int, default=4)
    ap.add_argument("--out", default=str(IMPL / "public" / "audio"))
    ap.add_argument("--check", action="store_true", help="exit non-zero when any QA issue is reported")
    ap.add_argument("--no-ts", action="store_true")
    a = ap.parse_args()
    _load_all()
    ids = sorted(registry.SPECS)
    if a.kind:
        ids = [i for i in ids if registry.SPECS[i].kind == a.kind]
    if a.only:
        ids = [i for i in ids if any(fnmatch.fnmatch(i, g) for g in a.only)]
    print(f"rendering {len(ids)} assets -> {a.out}")
    out_root = a.out
    with ProcessPoolExecutor(max_workers=a.jobs) as ex:
        recs = list(ex.map(render_one, [(i, out_root) for i in ids]))
    recs.sort(key=lambda r: r["id"])
    bad = [r for r in recs if r["qa"]]
    for r in recs:
        flag = "!!" if r["qa"] else "ok"
        print(f"{flag} {r['id']:<34} {r['duration']:>7.2f}s {r['bytes']:>8}B  LUFS {r['lufsI']}  tp {r['truePeakDb']}  {'; '.join(r['qa'])}")
    mf = Path(out_root) / "manifest.json"
    prev = {}
    if mf.exists() and (a.only or a.kind):             # partial run: merge into the existing manifest
        prev = {r["id"]: r for r in json.loads(mf.read_text())["assets"]}
    prev.update({r["id"]: r for r in recs})
    allrecs = sorted(prev.values(), key=lambda r: r["id"])
    mf.write_text(json.dumps({"version": 1, "generator": "tools/audio-gen/build_all.py", "licence": LICENSE_TEXT, "totalBytes": sum(r["bytes"] for r in allrecs), "assets": allrecs}, indent=1, ensure_ascii=False))
    if not a.no_ts:
        write_ts(allrecs)
    print(f"assets: {len(allrecs)}  total {sum(r['bytes'] for r in allrecs)/1024:.0f} KiB  QA issues: {len(bad)}")
    if a.check and bad:
        sys.exit(1)


def write_ts(recs):
    lines = ["/* GENERATED by tools/audio-gen/build_all.py. Do not edit by hand. */", "", "export type AssetKind = \"sfx\" | \"sfxloop\" | \"amb\" | \"music\" | \"stinger\";", "export type AssetBus = \"sfx\" | \"ui\" | \"music\" | \"amb\";",
             "export interface AssetMeta { readonly id: string; readonly url: string; readonly kind: AssetKind; readonly group: string; readonly bus: AssetBus; readonly loop: boolean; readonly channels: 1 | 2; readonly duration: number; readonly bytes: number; readonly lufsI: number | null; }", "",
             "export const AUDIO_ASSETS = {"]
    for r in recs:
        lines.append(f"  \"{r['id']}\": {{ id: \"{r['id']}\", url: \"/{r['file']}\", kind: \"{r['kind']}\", group: \"{r['group']}\", bus: \"{r['bus']}\", loop: {str(r['loop']).lower()}, channels: {r['channels']}, duration: {r['duration']}, bytes: {r['bytes']}, lufsI: {r['lufsI'] if r['lufsI'] is not None else 'null'} }},")
    lines += ["} as const satisfies Record<string, AssetMeta>;", "", "export type AudioAssetId = keyof typeof AUDIO_ASSETS;", ""]
    p = IMPL / "src" / "audio" / "registry" / "assets.generated.ts"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
