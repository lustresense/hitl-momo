#!/usr/bin/env python3
"""
R22 Workstream O (O01, K10) — Legal Hand Bounding-Box Dataset Audit & HANDS RGB-D Baseline Probe.

Audits all local R17-R20 caches, Owner telemetry files, and public hand bounding-box datasets for:
  1. Commercial-safe legal license eligibility (`CC BY 4.0` / `MIT` / `Apache-2.0` vs `HOLD_LICENSE` / `REJECT`).
  2. Presence of genuine independent human-annotated ground-truth bounding boxes (never pseudo-bbox
     generated by HandLandmarker landmarks!).
  3. Subject-disjoint train/val/locked-test split verification on `HANDS RGB-D` (`10.17632/ndrczc35bt.2`).
  4. Baseline `HandLandmarker` internal BlazePalm detector recall stratified by hand bbox size & subject
     against real independent GT bboxes on `HANDS RGB-D` (`S1..S5`, locked `S4+S5` OOD test).
"""
from __future__ import annotations

import collections
import json
import os
import time
import zipfile
from typing import Any

import numpy as np

R18_SANDBOX = "/srv/sketchbook/mediapipe-optimize/r18-ux0-sandbox"
R19_SANDBOX = "/srv/sketchbook/mediapipe-optimize/r19-sandbox"
R20_SANDBOX = "/srv/sketchbook/mediapipe-optimize/r20-sandbox"
OWNER_FOUR_TRIALS = (
    "/srv/sketchbook/mediapipe-optimize/research-can/docs/plan-rev/"
    "R22_FULL_SCOPE_MALAM_20261119/references/benchmarks/nui-lab-benchmark-S-07ba0cde-four-trials.json"
)
OUT_DIR = "/srv/sketchbook/mediapipe-optimize/research-can/r22/detector"
OUT_AUDIT = f"{OUT_DIR}/r22_legal_bbox_audit.json"
OUT_SPLITS = f"{OUT_DIR}/r22_hands_rgbd_bbox_splits.json"


def check_owner_json_has_no_images_or_bboxes() -> dict[str, Any]:
    with open(OWNER_FOUR_TRIALS, encoding="utf-8") as f:
        data = json.load(f)
    trials = data.get("trials", [])
    frames = data.get("frames", [])
    sample_keys = sorted(frames[0].keys()) if frames else []
    has_image_field = any(k in ("image", "rgba", "pixels", "video", "frameData") for k in sample_keys)
    has_gt_bbox = any(k in ("gt_bbox", "gt_bboxes", "bbox", "bboxes") for k in sample_keys)
    return {
        "file": os.path.basename(OWNER_FOUR_TRIALS),
        "bytes": os.path.getsize(OWNER_FOUR_TRIALS),
        "trials": len(trials),
        "frames": len(frames),
        "sample_frame_keys": sample_keys,
        "has_images": has_image_field,
        "has_independent_gt_bboxes": has_gt_bbox,
        "eligibility": "NOT_ELIGIBLE_TELEMETRY_ONLY",
        "note": "Contains numeric landmarks & telemetry only; landmark bounding boxes are detector outputs, NOT independent detector GT.",
    }


def check_ipn_hands_cache() -> dict[str, Any]:
    ann_zip = f"{R18_SANDBOX}/datasets/ipn_hands/IPN_HandS_annotations.zip"
    gt_zip = f"{R18_SANDBOX}/datasets/ipn_hands/IPN_HandS_landmarks_GT.zip"
    with zipfile.ZipFile(ann_zip) as za:
        ann_names = za.namelist()
    with zipfile.ZipFile(gt_zip) as zg:
        gt_names = zg.namelist()
        sample_gt = json.loads(zg.read(gt_names[0]).decode("utf-8"))
        first_frame = next(iter(sample_gt.values()))
        gt_keys = sorted(first_frame.keys()) if isinstance(first_frame, dict) else []
    return {
        "dataset_id": "ipn_hands",
        "license": "CC BY 4.0",
        "local_files": [os.path.basename(ann_zip), os.path.basename(gt_zip)],
        "annotation_entries": len(ann_names),
        "gt_json_files": len(gt_names),
        "sample_gt_frame_keys": gt_keys,
        "has_independent_gt_bboxes": any("bbox" in k.lower() or "box" in k.lower() for k in gt_keys),
        "eligibility": "NO_BBOX_LANDMARKS_AND_TEMPORAL_ONLY",
    }


def check_bxr7_cache() -> dict[str, Any]:
    dim_zip = f"{R18_SANDBOX}/datasets/mendeley_bxr7kx84y6/dim_light_1.zip"
    nat_zip = f"{R18_SANDBOX}/datasets/mendeley_bxr7kx84y6/natural_light_1.zip"
    info = {}
    for name, path in [("dim_light_1", dim_zip), ("natural_light_1", nat_zip)]:
        with zipfile.ZipFile(path) as z:
            files = [n for n in z.namelist() if not n.endswith("/")]
            non_img = [n for n in files if not n.lower().endswith((".jpg", ".jpeg", ".png"))]
            info[name] = {"files": len(files), "non_image_files": non_img}
    return {
        "dataset_id": "mendeley_bxr7kx84y6_v2",
        "license": "CC BY 4.0",
        "archives": info,
        "has_independent_gt_bboxes": False,
        "eligibility": "NO_BBOX_UNLABELED_IMAGES_ONLY",
    }


def check_hg5g_and_natural_rgb() -> list[dict[str, Any]]:
    hg_path = f"{R19_SANDBOX}/data/handgesture_5g_derived/handgesture_5g_landmarks.jsonl"
    n66_path = f"{R19_SANDBOX}/data/n66hhk695h_v3_derived/n66hhk695h_v3_landmarks.jsonl"
    out = []
    for did, lic, path in [
        ("handgesture_5g", "CC BY 4.0", hg_path),
        ("natural_rgb_v3", "CC BY 4.0", n66_path),
    ]:
        with open(path, encoding="utf-8") as f:
            first = json.loads(f.readline())
        keys = sorted(first.keys())
        out.append({
            "dataset_id": did,
            "license": lic,
            "sample_keys": keys,
            "has_independent_gt_bboxes": any("gt_bbox" in k for k in keys),
            "eligibility": "NO_BBOX_IMAGE_LEVEL_GESTURE_CLASSES_ONLY",
        })
    return out


def audit_hands_rgbd_bboxes() -> tuple[dict[str, Any], dict[str, Any]]:
    path = f"{R19_SANDBOX}/data/hands_rgbd_eval/hands_rgbd_landmarks.jsonl"
    splits: dict[str, list[dict[str, Any]]] = {"train_s1_s2": [], "val_s3": [], "test_s4_s5_locked": []}
    subj_map = {
        "Subject1": "train_s1_s2",
        "Subject2": "train_s1_s2",
        "Subject3": "val_s3",
        "Subject4": "test_s4_s5_locked",
        "Subject5": "test_s4_s5_locked",
    }
    stats = collections.defaultdict(lambda: {
        "frames": 0,
        "gt_boxes": 0,
        "l0_matched": 0,
        "l1_matched": 0,
        "by_size_bucket": collections.defaultdict(lambda: {"n": 0, "l0_hit": 0, "l1_hit": 0}),
    })

    all_norm_dims: list[float] = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            r = json.loads(line)
            subj = r["subject"]
            sp = subj_map[subj]
            w, h = int(r["width"]), int(r["height"])
            gt_bboxes = r["gt_bboxes"]
            m_l0 = r.get("gt_match_l0", {})
            m_l1 = r.get("gt_match_l1", {})

            st = stats[sp]
            st["frames"] += 1
            norm_boxes = []
            for lbl, (bx, by, bw, bh) in gt_bboxes.items():
                st["gt_boxes"] += 1
                hit0 = m_l0.get(lbl) is not None
                hit1 = m_l1.get(lbl) is not None
                if hit0:
                    st["l0_matched"] += 1
                if hit1:
                    st["l1_matched"] += 1

                max_dim = max(bw / max(1, w), bh / max(1, h))
                all_norm_dims.append(max_dim)
                bucket = "tiny_lt_0.10" if max_dim < 0.10 else ("small_0.10_0.14" if max_dim < 0.14 else "medium_ge_0.14")
                bs = st["by_size_bucket"][bucket]
                bs["n"] += 1
                bs["l0_hit"] += int(hit0)
                bs["l1_hit"] += int(hit1)

                norm_boxes.append({
                    "label": lbl,
                    "xywh_px": [bx, by, bw, bh],
                    "xyxy_norm": [
                        round(bx / w, 5),
                        round(by / h, 5),
                        round((bx + bw) / w, 5),
                        round((by + bh) / h, 5),
                    ],
                })

            splits[sp].append({
                "sample_id": r["sample_id"],
                "subject": subj,
                "filename": r["filename"],
                "width": w,
                "height": h,
                "boxes": norm_boxes,
            })

    summary_splits = {}
    for sp, st in stats.items():
        n = max(1, st["gt_boxes"])
        buckets = {}
        for bk, bval in sorted(st["by_size_bucket"].items()):
            bn = max(1, bval["n"])
            buckets[bk] = {
                "gt_boxes": bval["n"],
                "l0_raw_recall": round(bval["l0_hit"] / bn, 4),
                "l1_clahe320_recall": round(bval["l1_hit"] / bn, 4),
            }
        summary_splits[sp] = {
            "frames": st["frames"],
            "gt_boxes": st["gt_boxes"],
            "l0_raw_matched": st["l0_matched"],
            "l0_raw_recall": round(st["l0_matched"] / n, 4),
            "l1_clahe320_matched": st["l1_matched"],
            "l1_clahe320_recall": round(st["l1_matched"] / n, 4),
            "by_hand_size_bucket": buckets,
        }

    audit_entry = {
        "dataset_id": "hands_rgbd_v2",
        "doi": "10.17632/ndrczc35bt.2",
        "license": "CC BY 4.0",
        "has_independent_gt_bboxes": True,
        "eligibility": "ELIGIBLE_INDEPENDENT_GT_BBOX",
        "curated_frames": sum(v["frames"] for v in summary_splits.values()),
        "curated_gt_boxes": sum(v["gt_boxes"] for v in summary_splits.values()),
        "full_dataset_note": "Subject1..5.zip on Mendeley contain 12,000 total frames across 5 subjects with GT [x,y,w,h] in Subject1..5.txt; 2,700 frames (5,250 boxes) already streamed and verified locally.",
        "norm_max_dim_percentiles": {
            "p10": round(float(np.percentile(all_norm_dims, 10)), 4),
            "p50": round(float(np.percentile(all_norm_dims, 50)), 4),
            "p90": round(float(np.percentile(all_norm_dims, 90)), 4),
        },
        "subject_disjoint_splits": summary_splits,
    }
    split_artifact = {
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "dataset": "HANDS RGB-D (10.17632/ndrczc35bt.2, CC BY 4.0)",
        "split_policy": "Strict subject-disjoint: S1+S2 train, S3 val, S4+S5 locked OOD test (zero overlap).",
        "counts": {k: len(v) for k, v in splits.items()},
        "splits": splits,
    }
    return audit_entry, split_artifact


def main() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    owner_check = check_owner_json_has_no_images_or_bboxes()
    ipn_check = check_ipn_hands_cache()
    bxr7_check = check_bxr7_cache()
    hg_n66_checks = check_hg5g_and_natural_rgb()
    hands_rgbd_entry, hands_rgbd_splits = audit_hands_rgbd_bboxes()

    excluded_catalog = [
        {
            "dataset_id": "hagridv2",
            "license": "Custom ShareAlike (license/en_us.pdf Sec 3(b) & 4)",
            "has_independent_gt_bboxes": True,
            "eligibility": "HOLD_LICENSE",
            "reason": "Requires Owner legal sign-off on Adapted Material ShareAlike obligations; strictly excluded from product weights.",
        },
        {
            "dataset_id": "egohands",
            "license": "Academic / non-commercial (Indiana University)",
            "has_independent_gt_bboxes": True,
            "eligibility": "REJECT_NON_COMMERCIAL",
            "reason": "Non-commercial academic provenance; also primary archive URL retired.",
        },
        {
            "dataset_id": "oxford_hands_100doh",
            "license": "Academic / research-only terms",
            "has_independent_gt_bboxes": True,
            "eligibility": "REJECT_OR_HOLD_NON_COMMERCIAL",
            "reason": "Not cleared for commercial product redistribution.",
        },
        {
            "dataset_id": "openimages_v7_hand",
            "license": "CC BY 4.0 annotations + per-image CC BY licenses",
            "has_independent_gt_bboxes": True,
            "eligibility": "CANDIDATE_REMOTE_ELIGIBLE_NOT_INGESTED",
            "reason": "Eligible backup if dedicated hand-only ObjectDetector training is approved later; skipped in R22 due to multi-GB download/storage budget.",
        },
    ]

    audit_report = {
        "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        "contract": "K10 (O01)",
        "sources_audited": [
            owner_check,
            hands_rgbd_entry,
            *hg_n66_checks,
            ipn_check,
            bxr7_check,
            *excluded_catalog,
        ],
        "summary": {
            "eligible_gt_bbox_datasets_local": ["hands_rgbd_v2"],
            "curated_gt_boxes_ready": hands_rgbd_entry["curated_gt_boxes"],
            "locked_ood_test_boxes": hands_rgbd_entry["subject_disjoint_splits"]["test_s4_s5_locked"]["gt_boxes"],
            "hold_license_confirmed": ["hagridv2"],
            "owner_json_has_bboxes": False,
            "baseline_hand_landmarker_locked_ood_recall": hands_rgbd_entry["subject_disjoint_splits"]["test_s4_s5_locked"]["l0_raw_recall"],
        },
    }

    with open(OUT_AUDIT, "w", encoding="utf-8") as f:
        json.dump(audit_report, f, indent=2)
    with open(OUT_SPLITS, "w", encoding="utf-8") as f:
        json.dump(hands_rgbd_splits, f)

    print(json.dumps(audit_report["summary"], indent=2))
    print("HANDS RGB-D splits:", json.dumps(hands_rgbd_entry["subject_disjoint_splits"], indent=2))


if __name__ == "__main__":
    main()
